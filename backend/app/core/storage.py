"""Private file storage for user uploads.

Files are never served directly: there is no public URL. Every download goes through the
API, which checks ownership first. Code outside this module only sees a `Storage` and
opaque keys, so the local folder can be swapped for a private cloud bucket (S3, Supabase
Storage, R2) by adding one class, with no change to the documents module.

Keys are generated by the server (random), never taken from user input; `_path` still
refuses anything that could escape the storage folder.
"""

import os
import re
import tempfile
from functools import lru_cache
from pathlib import Path
from typing import Protocol

from app.core.config import get_settings

_SAFE_KEY = re.compile(r"^[a-z0-9]+(?:/[a-z0-9][a-z0-9._-]*)*$")


class StorageError(Exception):
    """A storage operation failed (disk, bucket, permissions). Never shown to users."""


class Storage(Protocol):
    def save(self, key: str, data: bytes) -> None: ...

    def read(self, key: str) -> bytes: ...

    def delete(self, key: str) -> None:
        """Remove the object. Removing a missing object is not an error."""
        ...

    def exists(self, key: str) -> bool: ...


class LocalStorage:
    """Files in a private folder on the server's disk (development, single server)."""

    def __init__(self, root: Path) -> None:
        self.root = root.resolve()

    def _path(self, key: str) -> Path:
        if not _SAFE_KEY.match(key) or ".." in key:
            raise StorageError("invalid storage key")
        path = (self.root / key).resolve()
        if self.root not in path.parents:
            raise StorageError("invalid storage key")
        return path

    def save(self, key: str, data: bytes) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        # Write to a temporary file, then rename: a crash never leaves half a file.
        fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".upload-")
        try:
            with os.fdopen(fd, "wb") as f:
                f.write(data)
            os.replace(tmp, path)
        except OSError as exc:
            Path(tmp).unlink(missing_ok=True)
            raise StorageError("could not save file") from exc

    def read(self, key: str) -> bytes:
        try:
            return self._path(key).read_bytes()
        except OSError as exc:
            raise StorageError("could not read file") from exc

    def delete(self, key: str) -> None:
        try:
            self._path(key).unlink(missing_ok=True)
        except OSError as exc:
            raise StorageError("could not delete file") from exc

    def exists(self, key: str) -> bool:
        return self._path(key).is_file()


@lru_cache
def get_storage() -> Storage:
    """FastAPI dependency. Tests replace it with storage in a temporary folder."""
    settings = get_settings()
    if settings.storage_backend == "local":
        return LocalStorage(settings.storage_dir)
    raise RuntimeError(f"Unknown STORAGE_BACKEND: {settings.storage_backend}")
